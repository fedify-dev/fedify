/**
 * Analysis for the `vocab-clone-verifier` rule.
 *
 * Generated `clone()` methods of vocabulary objects do not inherit the
 * source's default `verifyPortableObject`, so a `get*()` accessor called on a
 * clone may dereference portable objects without verifying them.  The
 * analysis follows vocabulary objects through a program syntactically: it
 * cannot see whether an object actually has a default verifier, so it only
 * tracks which objects *may* have one.
 *
 * Each expression evaluates to one of these states:
 *
 *  -  `carrier`: a vocabulary object that may have a default verifier.
 *  -  `bare`: a vocabulary object known to have none, e.g., one constructed
 *     without a verifier.
 *  -  `dropped`: a `clone()` result that lost the default verifier of the
 *     object it was cloned from.  It remembers the first `clone()` call that
 *     dropped the verifier, and whether a later `clone()` dropped it again.
 *  -  `unknown`: anything else, which is never reported.
 *
 * A `get*()` accessor called on a `dropped` value without a verifier is
 * reported at the `clone()` call that dropped it.
 * @module
 */
import {
  ast,
  type Ast,
  children,
  expressionWrappers,
  isVocabularySource,
  name,
} from "./ast.ts";
import type { Node } from "./types.ts";

/** Options of the `vocab-clone-verifier` rule. */
export interface VocabCloneOptions {
  /**
   * Import specifiers of other vocabulary modules generated by
   * `@fedify/vocab-tools`, in addition to `@fedify/vocab`.
   */
  modules?: readonly string[];
}

/** A `clone()` call whose result is dereferenced without a verifier. */
export interface VocabCloneDiagnostic {
  /** The node to report: the `clone` property, or the call if computed. */
  node: Node;
  /**
   * Whether a later `clone()` without a verifier dropped the verifier again,
   * so that fixing only this call would not help.
   */
  rechained: boolean;
  /**
   * The `clone` identifier that a suggestion may replace with `deepClone`,
   * if replacing it alone would retain the verifier.
   */
  suggestionNode?: Node;
}

type State =
  | { kind: "carrier" }
  | { kind: "bare" }
  | { kind: "dropped"; origin: Ast; rechained: boolean }
  | { kind: "unknown" };

const CARRIER: State = { kind: "carrier" };
const BARE: State = { kind: "bare" };
const UNKNOWN: State = { kind: "unknown" };

interface Binding {
  kind: "import" | "variable" | "parameter" | "other";
  scope: Scope;
  /** For imports: `"builtin"`, `"custom"`, or absent for other modules. */
  source?: "builtin" | "custom";
  imported?: string;
  namespace?: boolean;
  typeOnly?: boolean;
  /** The initializer of a variable declared with a single identifier. */
  init?: Ast;
  /** The iterated expression of a `for-of` loop declaring this variable. */
  iterated?: Ast;
  /** The type annotation of a variable or parameter. */
  annotation?: Ast;
  /**
   * The lexical scope of the declaration, where its annotation is resolved;
   * a `var` binding itself is hoisted to the function scope.
   */
  declarationScope?: Scope;
  /** Reassigned, redeclared, or declared by a namespace or an enum. */
  opaque?: boolean;
}

/** The instance context of a class member. */
interface ThisContext {
  /** The class declaration or expression. */
  cls: Ast;
}

interface Scope {
  parent?: Scope;
  functionScope: boolean;
  bindings: Map<string, Binding>;
}

/** What an options argument says about `verifyPortableObject`. */
interface OptionsInfo {
  /**
   * `"none"`: no verifier is passed.  `"nullish"`: an explicit nullish
   * `verifyPortableObject`.  `"explicit"`: a verifier is, or may be, passed.
   */
  verifier: "none" | "nullish" | "explicit";
  /** `dereference: false` is definitely passed. */
  noDereference: boolean;
  /** `inheritPortableObjectVerifier: false` is definitely passed. */
  noInherit: boolean;
}

const EXPLICIT_OPTIONS: OptionsInfo = {
  verifier: "explicit",
  noDereference: false,
  noInherit: false,
};

const SCOPED_TYPES = new Set([
  "BlockStatement",
  "CatchClause",
  "ForStatement",
  "ForInStatement",
  "ForOfStatement",
  "SwitchStatement",
  "ClassExpression",
  "ClassDeclaration",
  "StaticBlock",
]);

const FUNCTION_TYPES = new Set([
  "FunctionDeclaration",
  "FunctionExpression",
  "ArrowFunctionExpression",
]);

const ACCESSOR_PATTERN = /^get[A-Z]/;

function lookup(scope: Scope | undefined, id: string): Binding | undefined {
  for (; scope; scope = scope.parent) {
    const binding = scope.bindings.get(id);
    if (binding) return binding;
  }
}

/** Strips TypeScript wrappers, parentheses, optional chains and `await`. */
function unwrapValue(node: Ast | undefined): Ast | undefined {
  while (
    node &&
    (expressionWrappers.has(node.type) ||
      node.type === "ChainExpression" ||
      node.type === "AwaitExpression")
  ) {
    node = ast(
      node.type === "AwaitExpression" ? node.argument : node.expression,
    );
  }
  return node;
}

/** Strips TypeScript wrappers and parentheses only. */
function unwrapTs(node: Ast | undefined): Ast | undefined {
  while (node && expressionWrappers.has(node.type)) node = ast(node.expression);
  return node;
}

/** The value of a string literal or a template literal without expressions. */
function staticString(node: Ast | undefined): string | undefined {
  if (node?.type === "Literal") {
    return typeof node.value === "string" ? node.value : undefined;
  }
  if (
    node?.type === "TemplateLiteral" &&
    (node.expressions as unknown[]).length === 0
  ) {
    const quasi = (node.quasis as Ast[])[0];
    const cooked =
      (quasi.value as { cooked?: string } | undefined)?.cooked ?? quasi.cooked;
    return typeof cooked === "string" ? cooked : undefined;
  }
}

/** The name a member expression accesses, when it is statically known. */
function memberName(member: Ast): string | undefined {
  const property = ast(member.property);
  if (!member.computed) {
    return property?.type === "Identifier"
      ? (property.name as string)
      : undefined;
  }
  return staticString(unwrapTs(property));
}

/** The source position of a node, for reporting in source order. */
function position(node: Ast): number {
  const range = node.range as [number, number] | undefined;
  return range?.[0] ?? (node.start as number | undefined) ?? 0;
}

/**
 * Finds `clone()` calls on vocabulary objects whose results are dereferenced
 * by `get*()` accessors without a verifier, and reports each of them once, in
 * source order.
 */
export function checkVocabClones(
  program: Node,
  options: VocabCloneOptions,
  report: (diagnostic: VocabCloneDiagnostic) => void,
): void {
  const sourceKind = (source: string | undefined) =>
    source == null
      ? undefined
      : isVocabularySource(source)
        ? "builtin"
        : options.modules?.includes(source)
          ? "custom"
          : undefined;

  // Imports are top-level statements, so a file importing no vocabulary
  // module has no vocabulary object to track:
  const body = (program as unknown as Ast).body;
  if (
    !Array.isArray(body) ||
    !body.some(
      (statement: Ast) =>
        statement.type === "ImportDeclaration" &&
        sourceKind(name(statement.source)) != null,
    )
  ) {
    return;
  }

  const scopes = new WeakMap<Ast, Scope>();
  /** The class whose instance `this` or `super` refers to, if any. */
  const thisClasses = new WeakMap<Ast, ThisContext | null>();
  const calls: Ast[] = [];
  /**
   * Calls inside a class member named `clone` or `deepClone`, where replacing
   * `clone()` with `deepClone()` could make the override call itself.
   */
  const callsInCloneOverrides = new WeakSet<Ast>();
  let cloneOverrideDepth = 0;
  const assignmentTargets: [Ast, Scope][] = [];
  const iteratedBy = new WeakMap<Ast, Ast>();
  const root: Scope = { functionScope: true, bindings: new Map() };

  function declare(scope: Scope, id: string, binding: Binding): void {
    const existing = scope.bindings.get(id);
    if (existing != null) {
      // A name declared twice, e.g., by two `var` declarations, may hold
      // either value:
      existing.opaque = true;
      return;
    }
    scope.bindings.set(id, binding);
  }

  /** Binds every identifier in a pattern as an untracked binding. */
  function bindPattern(pattern: unknown, scope: Scope): void {
    const node = ast(pattern);
    if (!node) return;
    if (node.type === "Identifier") {
      declare(scope, node.name as string, { kind: "other", scope });
    } else if (node.type === "TSParameterProperty") {
      bindPattern(node.parameter, scope);
    } else if (node.type === "RestElement") {
      bindPattern(node.argument, scope);
    } else if (node.type === "AssignmentPattern") {
      bindPattern(node.left, scope);
    } else if (node.type === "ObjectPattern") {
      for (const property of node.properties as Ast[]) {
        bindPattern(
          property.type === "RestElement" ? property.argument : property.value,
          scope,
        );
      }
    } else if (node.type === "ArrayPattern") {
      for (const element of node.elements as unknown[]) {
        bindPattern(element, scope);
      }
    }
  }

  function annotationOf(node: Ast): Ast | undefined {
    return ast(ast(node.typeAnnotation)?.typeAnnotation);
  }

  function bindParameter(param: unknown, scope: Scope): void {
    let node = ast(param);
    if (node?.type === "TSParameterProperty") node = ast(node.parameter);
    if (node?.type === "AssignmentPattern") node = ast(node.left);
    if (node?.type === "Identifier") {
      declare(scope, node.name as string, {
        kind: "parameter",
        scope,
        annotation: annotationOf(node),
      });
    } else {
      bindPattern(param, scope);
    }
  }

  /** Collects identifiers that an assignment target writes to. */
  function collectTargets(target: unknown, scope: Scope): void {
    const node = unwrapTs(ast(target));
    if (!node) return;
    if (node.type === "Identifier") {
      assignmentTargets.push([node, scope]);
    } else if (node.type === "RestElement") {
      collectTargets(node.argument, scope);
    } else if (node.type === "AssignmentPattern") {
      collectTargets(node.left, scope);
    } else if (node.type === "ObjectPattern") {
      for (const property of node.properties as Ast[]) {
        collectTargets(
          property.type === "RestElement" ? property.argument : property.value,
          scope,
        );
      }
    } else if (node.type === "ArrayPattern") {
      for (const element of node.elements as unknown[]) {
        collectTargets(element, scope);
      }
    }
  }

  function visitClass(
    node: Ast,
    outer: Scope,
    thisClass: ThisContext | null,
  ): void {
    if (node.type === "ClassDeclaration") bindPattern(node.id, outer);
    const scope: Scope = {
      parent: outer,
      functionScope: false,
      bindings: new Map(),
    };
    scopes.set(node, scope);
    if (node.type === "ClassExpression") bindPattern(node.id, scope);
    // The superclass and decorators are evaluated outside the class body:
    const superClass = ast(node.superClass);
    if (superClass) visit(superClass, outer, thisClass);
    for (const decorator of (node.decorators as unknown[] | undefined) ?? []) {
      const child = ast(decorator);
      if (child) visit(child, outer, thisClass);
    }
    const classBody = ast(node.body);
    if (!classBody) return;
    scopes.set(classBody, scope);
    for (const member of classBody.body as Ast[]) {
      scopes.set(member, scope);
      const key = ast(member.key);
      if (key && member.computed) visit(key, scope, thisClass);
      for (const decorator of (member.decorators as unknown[] | undefined) ??
        []) {
        const child = ast(decorator);
        if (child) visit(child, scope, thisClass);
      }
      const instance: ThisContext | null = member.static ? null : { cls: node };
      const memberName = member.computed
        ? staticString(unwrapTs(key))
        : name(key);
      const override = memberName === "clone" || memberName === "deepClone";
      if (override) cloneOverrideDepth++;
      if (member.type === "MethodDefinition") {
        const value = ast(member.value);
        if (value) visitFunction(value, scope, instance);
      } else if (
        member.type === "PropertyDefinition" ||
        member.type === "AccessorProperty"
      ) {
        const value = ast(member.value);
        if (value) visit(value, scope, instance);
      } else if (member.type === "StaticBlock") {
        visit(member, scope, null);
      } else {
        // Index signatures and other type-only members:
        for (const child of children(member)) visit(child, scope, null);
      }
      if (override) cloneOverrideDepth--;
    }
  }

  function visitFunction(
    node: Ast,
    outer: Scope,
    thisClass: ThisContext | null,
  ): void {
    if (node.type === "FunctionDeclaration") bindPattern(node.id, outer);
    const scope: Scope = {
      parent: outer,
      functionScope: true,
      bindings: new Map(),
    };
    scopes.set(node, scope);
    if (node.type === "FunctionExpression") bindPattern(node.id, scope);
    for (const param of node.params as unknown[]) bindParameter(param, scope);
    for (const child of children(node)) {
      if (child === node.id) continue;
      visit(child, scope, thisClass);
    }
  }

  function visit(node: Ast, outer: Scope, thisClass: ThisContext | null): void {
    if (
      node.type === "TSModuleDeclaration" ||
      node.type === "TSEnumDeclaration"
    ) {
      // Keep the enclosing binding opaque, including the first segment of a
      // dotted namespace name, and skip the body, as declaration merging can
      // make names in it refer to other values:
      let id = ast(node.id);
      while (id?.type === "TSQualifiedName") id = ast(id.left);
      if (id?.type === "Identifier") {
        declare(outer, id.name as string, {
          kind: "other",
          scope: outer,
          opaque: true,
        });
      }
      return;
    }
    if (node.type === "TSModuleBlock") return;
    if (node.type === "ClassDeclaration" || node.type === "ClassExpression") {
      visitClass(node, outer, thisClass);
      return;
    }
    if (FUNCTION_TYPES.has(node.type)) {
      // Only arrow functions keep the enclosing `this`:
      visitFunction(
        node,
        outer,
        node.type === "ArrowFunctionExpression" ? thisClass : null,
      );
      return;
    }
    const scope: Scope = SCOPED_TYPES.has(node.type)
      ? {
          parent: outer,
          functionScope: node.type === "StaticBlock",
          bindings: new Map(),
        }
      : outer;
    scopes.set(node, scope);
    switch (node.type) {
      case "ThisExpression":
      case "Super":
        thisClasses.set(node, thisClass);
        break;
      case "CallExpression":
        calls.push(node);
        if (cloneOverrideDepth > 0) callsInCloneOverrides.add(node);
        break;
      case "CatchClause":
        bindPattern(node.param, scope);
        break;
      case "TSImportEqualsDeclaration":
        bindPattern(node.id, scope);
        break;
      case "ImportDeclaration": {
        const source = sourceKind(name(node.source));
        for (const specifier of node.specifiers as Ast[]) {
          const local = ast(specifier.local);
          if (local?.type !== "Identifier") continue;
          // Vocabulary modules have no default export:
          const tracked =
            source != null && specifier.type !== "ImportDefaultSpecifier";
          declare(scope, local.name as string, {
            kind: tracked ? "import" : "other",
            scope,
            source,
            imported: name(specifier.imported),
            namespace: specifier.type === "ImportNamespaceSpecifier",
            typeOnly:
              node.importKind === "type" || specifier.importKind === "type",
          });
        }
        break;
      }
      case "VariableDeclaration": {
        let target = scope;
        if (node.kind === "var") {
          while (!target.functionScope && target.parent) target = target.parent;
        }
        const declarations = node.declarations as Ast[];
        const iterated = iteratedBy.get(node);
        for (const declaration of declarations) {
          const id = ast(declaration.id);
          if (id?.type === "Identifier") {
            declare(target, id.name as string, {
              kind: "variable",
              scope: target,
              init: ast(declaration.init),
              iterated: declarations.length === 1 ? iterated : undefined,
              annotation: annotationOf(id),
              declarationScope: scope,
            });
          } else {
            bindPattern(declaration.id, target);
          }
        }
        break;
      }
      case "AssignmentExpression":
        collectTargets(node.left, scope);
        break;
      case "UpdateExpression":
        collectTargets(node.argument, scope);
        break;
      case "ForInStatement":
      case "ForOfStatement": {
        const left = ast(node.left);
        if (left?.type === "VariableDeclaration") {
          if (node.type === "ForOfStatement") {
            const right = ast(node.right);
            if (right) iteratedBy.set(left, right);
          }
        } else {
          collectTargets(left, scope);
        }
        break;
      }
    }
    // ESTree providers also walk type annotations here, through enumerable
    // keys, while Deno does not; nothing below may depend on either, as no
    // call or binding the analysis tracks lives in a type position.
    for (const child of children(node)) {
      // The discriminant of a switch is evaluated outside its case scope:
      visit(
        child,
        node.type === "SwitchStatement" && child === node.discriminant
          ? outer
          : scope,
        thisClass,
      );
    }
  }

  visit(program as unknown as Ast, root, null);

  for (const [target, scope] of assignmentTargets) {
    const binding = lookup(scope, target.name as string);
    if (binding) binding.opaque = true;
  }

  const isUndefined = (node: Ast): boolean =>
    node.type === "Identifier" &&
    node.name === "undefined" &&
    lookup(scopes.get(node), "undefined") == null;

  const isVoid = (node: Ast): boolean =>
    node.type === "UnaryExpression" && node.operator === "void";

  const isNullLiteral = (node: Ast): boolean =>
    node.type === "Literal" && node.value === null && node.raw === "null";

  /** The import binding an identifier refers to, if any. */
  function importOf(node: Ast | undefined): Binding | undefined {
    if (node?.type !== "Identifier") return;
    const binding = lookup(scopes.get(node), node.name as string);
    return binding?.kind === "import" && !binding.opaque ? binding : undefined;
  }

  /** Whether an expression refers to a value export of a vocabulary module. */
  function isVocabularyValue(node: Ast | undefined): boolean {
    node = unwrapTs(node);
    if (node?.type === "Identifier") {
      const binding = importOf(node);
      return (
        binding != null &&
        !binding.typeOnly &&
        !binding.namespace &&
        binding.imported !== "lookupObject"
      );
    }
    if (node?.type === "MemberExpression") {
      const binding = importOf(unwrapTs(ast(node.object)));
      return (
        binding != null &&
        binding.namespace === true &&
        !binding.typeOnly &&
        memberName(node) != null &&
        memberName(node) !== "lookupObject"
      );
    }
    return false;
  }

  /** Whether a callee is `lookupObject()` from the built-in module. */
  function isLookupObject(callee: Ast | undefined): boolean {
    callee = unwrapTs(callee);
    if (callee?.type === "Identifier") {
      const binding = importOf(callee);
      return (
        binding?.source === "builtin" &&
        !binding.typeOnly &&
        !binding.namespace &&
        binding.imported === "lookupObject"
      );
    }
    if (callee?.type === "MemberExpression") {
      const binding = importOf(unwrapTs(ast(callee.object)));
      return (
        binding?.source === "builtin" &&
        binding.namespace === true &&
        !binding.typeOnly &&
        memberName(callee) === "lookupObject"
      );
    }
    return false;
  }

  /**
   * Classifies a type annotation: `"vocab"` for a vocabulary type, possibly
   * in a union with `null` or `undefined`, `"nullish"` for `null` or
   * `undefined` alone, and `"other"` for anything else.
   */
  function typeKind(
    node: Ast | undefined,
    scope: Scope,
  ): "vocab" | "nullish" | "other" {
    while (node?.type === "TSParenthesizedType") {
      node = ast(node.typeAnnotation);
    }
    if (!node) return "other";
    if (
      node.type === "TSNullKeyword" ||
      node.type === "TSUndefinedKeyword" ||
      (node.type === "TSLiteralType" &&
        isNullLiteral(ast(node.literal) ?? node))
    ) {
      return "nullish";
    }
    if (node.type === "TSUnionType") {
      let vocab = false;
      for (const member of node.types as Ast[]) {
        const kind = typeKind(member, scope);
        if (kind === "other") return "other";
        if (kind === "vocab") vocab = true;
      }
      return vocab ? "vocab" : "nullish";
    }
    if (node.type !== "TSTypeReference") return "other";
    if ((node.typeArguments ?? node.typeParameters) != null) return "other";
    const typeName = ast(node.typeName);
    let id: Ast | undefined;
    let qualified = false;
    if (typeName?.type === "Identifier") {
      id = typeName;
    } else if (typeName?.type === "TSQualifiedName") {
      id = ast(typeName.left);
      qualified = true;
    }
    if (id?.type !== "Identifier") return "other";
    const binding = lookup(scope, id.name as string);
    if (binding?.kind !== "import" || binding.opaque) return "other";
    return binding.namespace === qualified ? "vocab" : "other";
  }

  /** Analyzes an options argument, as described in {@link OptionsInfo}. */
  function optionsAt(args: Ast[], index: number): OptionsInfo {
    for (let i = 0; i <= index && i < args.length; i++) {
      if (args[i].type === "SpreadElement") return EXPLICIT_OPTIONS;
    }
    const arg = unwrapTs(args[index]);
    if (arg == null || isUndefined(arg) || isVoid(arg)) {
      return { verifier: "none", noDereference: false, noInherit: false };
    }
    if (arg.type !== "ObjectExpression") return EXPLICIT_OPTIONS;
    // The last definite value of each key; `null` marks a key that something
    // unknown, such as a spread, may have overwritten:
    const values = new Map<string, Ast | null>();
    let unknownRest = false;
    const keys = [
      "verifyPortableObject",
      "dereference",
      "inheritPortableObjectVerifier",
    ];
    const invalidate = () => {
      unknownRest = true;
      for (const key of keys) values.set(key, null);
    };
    for (const property of arg.properties as Ast[]) {
      if (property.type !== "Property") {
        invalidate();
        continue;
      }
      const keyNode = ast(property.key);
      let key: string | undefined;
      if (property.computed) {
        key = staticString(unwrapTs(keyNode));
        if (key == null) {
          invalidate();
          continue;
        }
      } else if (keyNode?.type === "Identifier") {
        key = keyNode.name as string;
      } else {
        key = staticString(keyNode);
      }
      if (
        key === "__proto__" &&
        !property.computed &&
        !property.shorthand &&
        !property.method &&
        property.kind === "init"
      ) {
        // This sets the prototype, which may supply any option:
        invalidate();
        continue;
      }
      if (key == null || !keys.includes(key)) continue;
      // Accessors and methods supply a value that is not statically known:
      values.set(
        key,
        property.kind === "init" && !property.method
          ? (unwrapTs(ast(property.value)) ?? null)
          : null,
      );
    }
    const verifierValue = values.get("verifyPortableObject");
    let verifier: OptionsInfo["verifier"];
    if (verifierValue === undefined) {
      verifier = unknownRest ? "explicit" : "none";
    } else if (verifierValue === null) {
      verifier = "explicit";
    } else {
      verifier =
        isUndefined(verifierValue) ||
        isVoid(verifierValue) ||
        isNullLiteral(verifierValue)
          ? "nullish"
          : "explicit";
    }
    const isFalse = (key: string): boolean => {
      const value = values.get(key);
      return value != null && value.type === "Literal" && value.value === false;
    };
    return {
      verifier,
      noDereference: isFalse("dereference"),
      noInherit: isFalse("inheritPortableObjectVerifier"),
    };
  }

  const states = new Map<Ast, State>();
  const bindingStates = new Map<Binding, State>();
  const inProgress = new Set<object>();
  /** Offending `clone()` calls, and whether any path re-cloned them. */
  const offenders = new Map<Ast, boolean>();

  function bindingState(binding: Binding): State {
    if (binding.opaque) return UNKNOWN;
    const known = bindingStates.get(binding);
    if (known) return known;
    // A cyclic alias, such as `var a = b; var b = a;`, holds no known value:
    if (inProgress.has(binding)) return UNKNOWN;
    inProgress.add(binding);
    let state = UNKNOWN;
    if (binding.kind === "variable") {
      if (binding.init) state = evaluate(binding.init);
      if (state.kind === "unknown" && binding.iterated) {
        const iterated = unwrapValue(binding.iterated);
        if (iterated?.type === "CallExpression" && isAccessorCall(iterated)) {
          state = evaluate(iterated);
        }
      }
    }
    if (
      state.kind === "unknown" &&
      (binding.kind === "variable" || binding.kind === "parameter") &&
      binding.annotation &&
      typeKind(
        binding.annotation,
        binding.declarationScope ?? binding.scope,
      ) === "vocab"
    ) {
      state = CARRIER;
    }
    inProgress.delete(binding);
    bindingStates.set(binding, state);
    return state;
  }

  function isAccessorCall(call: Ast): boolean {
    const callee = unwrapValue(ast(call.callee));
    if (callee?.type !== "MemberExpression") return false;
    const method = memberName(callee);
    return method != null && ACCESSOR_PATTERN.test(method);
  }

  function evaluate(expression: Ast): State {
    const node = unwrapValue(expression);
    if (!node) return UNKNOWN;
    const known = states.get(node);
    if (known) return known;
    if (inProgress.has(node)) return UNKNOWN;
    inProgress.add(node);
    const state = evaluateNode(node);
    inProgress.delete(node);
    states.set(node, state);
    return state;
  }

  function evaluateNode(node: Ast): State {
    switch (node.type) {
      case "Identifier": {
        const binding = lookup(scopes.get(node), node.name as string);
        return binding ? bindingState(binding) : UNKNOWN;
      }
      case "ThisExpression":
      case "Super": {
        const context = thisClasses.get(node);
        return context != null && isVocabularyValue(ast(context.cls.superClass))
          ? CARRIER
          : UNKNOWN;
      }
      case "NewExpression":
        if (!isVocabularyValue(ast(node.callee))) return UNKNOWN;
        return optionsAt(node.arguments as Ast[], 1).verifier === "explicit"
          ? CARRIER
          : BARE;
      case "CallExpression":
        return evaluateCall(node);
      default:
        return UNKNOWN;
    }
  }

  function evaluateCall(call: Ast): State {
    const args = call.arguments as Ast[];
    const rawCallee = ast(call.callee);
    if (isLookupObject(unwrapValue(rawCallee))) {
      return optionsAt(args, 1).verifier === "explicit" ? CARRIER : BARE;
    }
    const callee = unwrapValue(rawCallee);
    if (callee?.type !== "MemberExpression") return UNKNOWN;
    const method = memberName(callee);
    if (method == null) return UNKNOWN;
    const object = ast(callee.object);
    if (method === "fromJsonLd" && isVocabularyValue(unwrapValue(object))) {
      return optionsAt(args, 1).verifier === "explicit" ? CARRIER : BARE;
    }
    const isClone = method === "clone";
    const isDeepClone = method === "deepClone";
    const isAccessor = ACCESSOR_PATTERN.test(method);
    if (!isClone && !isDeepClone && !isAccessor) return UNKNOWN;
    const receiver = object ? evaluate(object) : UNKNOWN;
    if (receiver.kind === "unknown") return UNKNOWN;
    if (isClone) {
      const { verifier } = optionsAt(args, 1);
      if (verifier === "explicit") return CARRIER;
      if (verifier === "nullish" || receiver.kind === "bare") return BARE;
      return receiver.kind === "dropped"
        ? { kind: "dropped", origin: receiver.origin, rechained: true }
        : { kind: "dropped", origin: call, rechained: false };
    }
    if (isDeepClone) {
      // deepClone() falls back to the receiver's own default:
      if (receiver.kind === "carrier") return CARRIER;
      return optionsAt(args, 1).verifier === "explicit" ? CARRIER : receiver;
    }
    const info = optionsAt(args, 0);
    if (
      receiver.kind === "dropped" &&
      info.verifier === "none" &&
      !info.noDereference
    ) {
      offenders.set(
        receiver.origin,
        (offenders.get(receiver.origin) ?? false) || receiver.rechained,
      );
    }
    if (receiver.kind === "carrier") return CARRIER;
    return info.verifier === "explicit" &&
      !info.noInherit &&
      !info.noDereference
      ? CARRIER
      : UNKNOWN;
  }

  for (const call of calls) evaluate(call);

  const sorted = [...offenders].sort(([a], [b]) => position(a) - position(b));
  for (const [call, rechained] of sorted) {
    const callee = unwrapValue(ast(call.callee))!;
    const property = ast(callee.property)!;
    // Inside a clone() or deepClone() override, deepClone() could end up
    // calling the override again, which would call deepClone() again:
    const recursive = callsInCloneOverrides.has(call);
    report({
      node: (callee.computed ? call : property) as unknown as Node,
      rechained,
      suggestionNode:
        !rechained &&
        !recursive &&
        !callee.computed &&
        property.type === "Identifier"
          ? (property as unknown as Node)
          : undefined,
    });
  }
}
