import { readFileSync } from "node:fs";

const config = JSON.parse(
  readFileSync(
    process.argv[2] ?? new URL("../deno.json", import.meta.url),
    "utf8",
  ),
);
if (config.nodeModulesDir !== "none") {
  console.error(
    'Set nodeModulesDir to "none" so Deno preserves pnpm workspace links.',
  );
  process.exitCode = 1;
}
