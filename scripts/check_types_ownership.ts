/**
 * Ownership of TypeScript files that the default type check does not cover.
 *
 * `mise run check:types` requires every TypeScript file under *packages/*,
 * *scripts/*, and the other Node.js-owned paths to belong to a type-checking
 * project, unless an entry below assigns it to another check and explains
 * why.  Deno workspace membership alone never counts as coverage: an entry is
 * needed even when `deno check` also checks the file.
 *
 * Shared by *scripts/check\_types.ts* and *scripts/check\_types\_deno.ts*.
 * @module
 */

/** A file or directory that another check owns. */
export interface Ownership {
  /**
   * A repository-relative path or glob (`*` within a path segment, `**`
   * across segments).
   */
  readonly path: string;
  /** The check that type-checks or otherwise validates the matched files. */
  readonly owner: string;
  /** Why the default Node.js-based type check does not cover them. */
  readonly reason: string;
}

